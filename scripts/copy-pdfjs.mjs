// Copies the pdf.js legacy build (pdfjs-dist, Apache-2.0) into assets/pdfjs/ for the app's read-back and exact
// preview page (D15; loaded by the WebView harness, src/readback/harness-page.ts) and writes the same two files as
// string constants into src/readback/pdfjs.generated.ts (D70: the app embeds them as text — no asset download, the
// same bytes in dev and release builds). The Node referee uses the same version straight from node_modules.
// Run: node scripts/copy-pdfjs.mjs
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = join(root, 'node_modules', 'pdfjs-dist');
const { version } = JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8'));
const out = join(root, 'assets', 'pdfjs');
for (const file of ['pdf.min.mjs', 'pdf.worker.min.mjs']) copyFileSync(join(pkg, 'legacy', 'build', file), join(out, file));
copyFileSync(join(pkg, 'LICENSE'), join(out, 'LICENSE'));
writeFileSync(join(out, 'VERSION'), `pdfjs-dist ${version} (legacy build)\n`);
const src = (file) => JSON.stringify(readFileSync(join(out, file), 'utf8'));
writeFileSync(
  join(root, 'src', 'readback', 'pdfjs.generated.ts'),
  `// GENERATED by scripts/copy-pdfjs.mjs from pdfjs-dist ${version} legacy build (Apache-2.0, assets/pdfjs/LICENSE).\n` +
    '// Do not edit by hand. The WebView harness loads these texts from blob: URLs (D51, D70).\n' +
    `export const PDFJS_VERSION = ${JSON.stringify(version)};\n` +
    `export const PDFJS_SOURCE: string = ${src('pdf.min.mjs')};\n` +
    `export const PDFJS_WORKER_SOURCE: string = ${src('pdf.worker.min.mjs')};\n` +
    '// assets/warmup/warmup.pdf (a 1-page cover letter printed on the iOS simulator in P5): the page reads it once at load,\n' +
    '// because WKWebView sometimes hangs on the first getTextContent of a fresh page (D71).\n' +
    `export const WARMUP_PDF_BASE64 = ${JSON.stringify(readFileSync(join(root, 'assets', 'warmup', 'warmup.pdf')).toString('base64'))};\n`
);
console.log(`copied pdfjs-dist ${version} legacy build to assets/pdfjs/ and src/readback/pdfjs.generated.ts`);
