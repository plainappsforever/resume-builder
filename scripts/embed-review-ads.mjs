// Writes src/debug/review-ads.generated.ts: the reviewer's 4 job ads (src/engine/__fixtures__/job-ads-review/*.txt) as strings,
// for the DEV-ONLY recall screen (`debug/recall`) and the dev link `debug/ad?name=<ad>` — the keyword engine's recall run on
// the phone itself (P6 device check). Only required under __DEV__, so release bundles do not contain the ads.
// Usage: node scripts/embed-review-ads.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const dir = 'src/engine/__fixtures__/job-ads-review';
const expected = JSON.parse(readFileSync(`${dir}/expected.json`, 'utf8'));
const ads = Object.fromEntries(Object.keys(expected).map((name) => [name, readFileSync(`${dir}/${name}.txt`, 'utf8')]));
writeFileSync(
  'src/debug/review-ads.generated.ts',
  `// Generated by scripts/embed-review-ads.mjs — do not edit by hand.\nexport const REVIEW_ADS: Record<string, string> = ${JSON.stringify(ads, null, 2)};\n`
);
console.log(`${Object.keys(ads).length} ads`);
